//! Routine state and callback identifiers (`ZS_*` / `PS_*` names in the script registry).

macro_rules! states {
    ($($v:ident => $s:literal,)*) => {
        /// A script state/task name. `name()` is the registry string the engine uses.
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
        pub enum State { $($v,)* }
        impl State {
            /// Every state.
            pub const ALL: &'static [State] = &[$(State::$v,)*];
            /// Registry name (`ZS_Smith`).
            pub const fn name(self) -> &'static str { match self { $(State::$v => $s,)* } }
            /// Look a state up by registry name.
            pub fn from_name(name: &str) -> Option<State> {
                match name { $($s => Some(State::$v),)* _ => None }
            }
        }
    };
}

