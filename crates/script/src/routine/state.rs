/// Task / local callbacks an NPC can have registered (`SetTaskCallback`, `SetLocalCallback`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Callback {
    /// No callback.
    None,
    /// `OnGoto`: fired while travelling to the work point.
    OnGoto,
    /// `OnWork`: fired once the NPC stands on its work point.
    OnWork,
    /// `OnSleep`.
    OnSleep,
    /// `OnAnimalSleep`.
    OnAnimalSleep,
    /// `OnGateGuard`.
    OnGateGuard,
    /// `OnFollowPlayer`.
    OnFollowPlayer,
    /// `OnWaitForPlayer`.
    OnWaitForPlayer,
    /// `OnGuidePlayer`.
    OnGuidePlayer,
    /// `OnFollowNPC`.
    OnFollowNpc,
    /// `OnAttack_Goto`: per-tick callback of the approach in `ZS_Attack_Goto`/`Sprint`.
    OnAttackGoto,
    /// `OnAttack_Positioning`: callback of `ZS_Attack_ChangePosition`.
    OnAttackPositioning,
    /// `OnAttack_GoBack`.
    OnAttackGoBack,
    /// `OnAttack_Strafe`.
    OnAttackStrafe,
    /// `OnAttack_Turn`.
    OnAttackTurn,
    /// `OnReactToDamage`.
    OnReactToDamage,
    /// `OnReactToDamage_GoBack`.
    OnReactToDamageGoBack,
    /// `OnReactToWeapon`.
    OnReactToWeapon,
    /// `OnReactToZone`.
    OnReactToZone,
    /// `OnWatchFight`.
    OnWatchFight,
    /// `OnWatchFight_GoBack`.
    OnWatchFightGoBack,
    /// `OnWatchFight_Goto`.
    OnWatchFightGoto,
    /// `OnFlee_GotoFleePoint`.
    OnFleeGotoFleePoint,
    /// `OnFlee_GoBack`.
    OnFleeGoBack,
    /// `OnEatBody_Perception`.
    OnEatBodyPerception,
    /// `OnRansackBody`.
    OnRansackBody,
    /// `OnArena`.
    OnArena,
    /// `OnRevolutionAttack`.
    OnRevolutionAttack,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_round_trip() {
        for s in State::ALL {
            assert_eq!(State::from_name(s.name()), Some(*s));
        }
        assert_eq!(State::SmithAnvil.name(), "ZS_Smith_Anvil");
        assert_eq!(State::PsNormal.name(), "PS_Normal");
        assert_eq!(State::from_name("ZS_Nope"), None);
    }
}
