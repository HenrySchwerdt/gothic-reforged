//! Writes into a local remaster profile directory (see `gothic_formats::remaster`).
use anyhow::{Context, Result, ensure};
use gothic_formats::remaster::key_of;
use std::path::{Path, PathBuf};

pub struct ProfileWriter {
    pub root: PathBuf,
    lines: Vec<(String, String, String, Option<String>)>,
}

impl ProfileWriter {
    pub fn open(root: &Path) -> Result<Self> {
        std::fs::create_dir_all(root).with_context(|| format!("creating {}", root.display()))?;
        let mut lines = Vec::new();
        if let Ok(text) = std::fs::read_to_string(root.join("manifest.txt")) {
            for line in text.lines() {
                let l = line.split('#').next().unwrap_or("").trim();
                let mut it = l.split_whitespace();
                if let (Some(k), Some(n), Some(f)) = (it.next(), it.next(), it.next()) {
                    lines.push((k.to_string(), n.to_string(), f.to_string(), it.next().map(str::to_string)));
                }
            }
        }
        Ok(Self {
            root: root.to_path_buf(),
            lines,
        })
    }

    pub fn write_file(&self, rel: &str, bytes: &[u8]) -> Result<()> {
        ensure!(!rel.contains(".."), "file name escapes the profile");
        let path = self.root.join(rel);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&path, bytes).with_context(|| format!("writing {}", path.display()))
    }

    /// Adds or replaces the entry for `(kind, name)`.
    pub fn set(&mut self, kind: &str, name: &str, rel: &str) {
        self.set_with(kind, name, rel, None);
    }

    /// As [`Self::set`] with an option token such as `scale=3.5`.
    pub fn set_with(&mut self, kind: &str, name: &str, rel: &str, option: Option<String>) {
        let key = key_of(name);
        self.lines.retain(|(k, n, _, _)| !(k == kind && key_of(n) == key));
        self.lines.push((kind.into(), name.into(), rel.into(), option));
    }

    pub fn save(&self) -> Result<()> {
        let mut text = String::from(
            "# Gothic Reforged local remaster profile (generated by tools/gothic-assets).\n\
             # Derived from original assets: local use only, never commit or redistribute.\n",
        );
        for (k, n, f, o) in &self.lines {
            match o {
                Some(o) => text.push_str(&format!("{k} {n} {f} {o}\n")),
                None => text.push_str(&format!("{k} {n} {f}\n")),
            }
        }
        std::fs::write(self.root.join("manifest.txt"), text)?;
        Ok(())
    }
}
